const assert=require('node:assert/strict'),compile=require('./compile.cjs');
const {canMove,filterRetablos,countByEstado,tipoLabel}=compile('lib/retablos.ts');
assert(canMove('PENDIENTE','PENDIENTE_RECOGER'));assert(!canMove('PENDIENTE','ENTREGADO'));
assert(canMove('PENDIENTE_RECOGER','ENTREGADO'));assert(canMove('PENDIENTE_RECOGER','PENDIENTE'));
assert(!canMove('ENTREGADO','PENDIENTE'));assert(!canMove('ENTREGADO','PENDIENTE_RECOGER'));
const r=(o)=>({id:'1',contrato_id:'c',numero_contrato:'4581',tipo_id:'t1',tipo:'Retablo 10x40',cliente_nombre:'María Pérez',cliente_cedula:'1.121.000.000',numero_factura:'FV-00123',valor_cliente:250000,valor_empresa:100000,estado:'PENDIENTE',asesora_id:null,asesora:'Ana',sede:null,observaciones:'',creado_en:'2026-10-22T15:00:00Z',entregado_en:null,...o});
const rows=[r(),r({id:'2',cliente_nombre:'José Gómez',cliente_cedula:'52000111',numero_factura:'FV-9',estado:'ENTREGADO',tipo_id:'t2',asesora:'Luz',creado_en:'2026-10-01T15:00:00Z'})];
const ids=(f)=>JSON.stringify(filterRetablos(rows,{q:'',estado:'',tipo:'',desde:'',hasta:'',asesora:'',...f}).map(x=>x.id));
assert.equal(ids({q:'maria'}),'["1"]');
assert.equal(ids({q:'1121000000'}),'["1"]');
assert.equal(ids({q:'fv-9'}),'["2"]');
assert.equal(ids({q:'4581'}),'["1","2"]');
assert.equal(ids({estado:'ENTREGADO'}),'["2"]');
assert.equal(ids({tipo:'t1'}),'["1"]');
assert.equal(ids({desde:'2026-10-10'}),'["1"]');
assert.equal(ids({hasta:'2026-10-10'}),'["2"]');
assert.equal(ids({asesora:'Luz'}),'["2"]');
const c=countByEstado(rows);assert.equal(c.PENDIENTE,1);assert.equal(c.ENTREGADO,1);assert.equal(c.PENDIENTE_RECOGER,0);
assert.equal(tipoLabel({nombre:'Retablo 10x40',valor_cliente:250000},v=>'$'+v),'Retablo 10x40 — $250000');
console.log('PASS retablos: allowed status moves (Entregado final), panel filters and counters, type label');
