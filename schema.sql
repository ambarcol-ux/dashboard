-- ==============================================================================
-- 0. Tabla: sedes
-- Propósito: Maestro de sucursales/sedes físicas de la boutique.
-- ==============================================================================
CREATE TABLE sedes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre TEXT UNIQUE NOT NULL,
    activo BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 1. Tabla: profiles
-- Propósito: Extiende la información de los usuarios gestionados por Supabase Auth (auth.users).
-- Almacena el nombre, rol del usuario (por ejemplo, admin, usuario regular) y la sede a la que pertenece.
-- ==============================================================================
CREATE TABLE profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    rol TEXT NOT NULL,
    sede TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 2. Tabla: contratos
-- Propósito: Almacena la información de los contratos generados para los clientes.
-- Incluye datos sobre el contrato, el cliente, estado de pagos y firmas digitales.
-- ==============================================================================
CREATE TABLE contratos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    numero_contrato TEXT UNIQUE NOT NULL,
    estado TEXT NOT NULL DEFAULT 'borrador', 
    sede TEXT NOT NULL,
    cliente_nombre TEXT NOT NULL,
    cliente_documento TEXT NOT NULL,
    cliente_whatsapp TEXT NOT NULL,
    cliente_direccion TEXT,
    cliente_email TEXT NOT NULL,
    
    -- Logistica ERP
    tipo_evento TEXT DEFAULT 'Evento',
    tipo_entrega TEXT DEFAULT 'Local',
    asesora TEXT, -- Nombre para visualización rápida/congelada
    asesora_id UUID REFERENCES asesoras(id) ON DELETE SET NULL,
    sede_id UUID REFERENCES sedes(id) ON DELETE SET NULL,
    
    -- Fechas
    fecha_evento DATE NOT NULL,
    fecha_pre_xv TIMESTAMP,
    fecha_cita_medidas DATE,
    fecha_prueba_final DATE,
    fecha_entrega_envio DATE,
    
    valor_total NUMERIC NOT NULL,
    total_arreglos NUMERIC DEFAULT 0,
    anticipo NUMERIC DEFAULT 0,
    saldo NUMERIC GENERATED ALWAYS AS (valor_total + total_arreglos - anticipo) STORED,
    valor_deposito NUMERIC,
    
    -- Calidad Logistica
    estado_medidas TEXT DEFAULT 'Pendiente',
    estado_prueba_final TEXT DEFAULT 'Pendiente',
    estado_entrega_envio TEXT DEFAULT 'Pendiente',
    
    accesorios TEXT[],
    metodos_pago TEXT[],
    
    -- Deposito
    banco_deposito TEXT,
    tipo_cuenta_deposito TEXT,
    numero_cuenta_deposito TEXT,
    titular_cuenta_deposito TEXT,

    firma_base64 TEXT, 
    fecha_firma_cliente TIMESTAMP WITH TIME ZONE, 
    token_firma TEXT, 
    url_pdf_firmado TEXT, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 3. Tabla: pagos
-- Propósito: Permite rastrear y registrar los pagos parciales o totales 
-- vinculados a un contrato específico.
-- ==============================================================================
CREATE TABLE pagos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contrato_id UUID NOT NULL REFERENCES contratos(id) ON DELETE CASCADE,
    fecha_pago DATE NOT NULL,
    medio_pago TEXT NOT NULL, -- Ej: efectivo, transferencia, tarjeta
    valor_pagado NUMERIC NOT NULL,
    observaciones TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 4. Tabla: vestidos (Catálogo Maestro)
-- Propósito: Almacena el inventario central de vestidos.
-- ==============================================================================
CREATE TABLE vestidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT UNIQUE NOT NULL,
    categoria TEXT,
    descripcion TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 5. Tabla: contrato_items_vestidos
-- Propósito: Almacena múltiples vestidos (referenciando el ID numérico) vinculados a un contrato.
-- ==============================================================================
CREATE TABLE contrato_items_vestidos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contrato_id UUID NOT NULL REFERENCES contratos(id) ON DELETE CASCADE,
    vestido_id BIGINT NOT NULL REFERENCES vestidos(id) ON DELETE RESTRICT,
    tipo_uso TEXT NOT NULL DEFAULT 'XV',
    observaciones TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 6. Tabla: arreglos
-- Propósito: Almacena los arreglos a realizar en un contrato.
-- ==============================================================================
CREATE TABLE arreglos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contrato_id UUID NOT NULL REFERENCES contratos(id) ON DELETE CASCADE,
    tipo TEXT NOT NULL,
    cm TEXT NOT NULL,
    precio NUMERIC DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 7. Tabla: bitacora_cambios
-- Propósito: Auditoría estricta para registrar motivaciones de inasistencia,
-- penalizaciones o re-validación de fechas del inventario (QC Module).
-- ==============================================================================
CREATE TABLE bitacora_cambios (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contrato_id UUID NOT NULL REFERENCES contratos(id) ON DELETE CASCADE,
    tipo_evento TEXT NOT NULL, -- Ej: 'Inasistencia Cita', 'Inasistencia Prueba', 'Cambio Fecha Cita'
    motivo TEXT NOT NULL,
    fecha_anterior TIMESTAMP,
    fecha_nueva TIMESTAMP,
    usuario_id UUID REFERENCES auth.users(id) ON DELETE SET NULL, -- Asesora que registra el cambio
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

