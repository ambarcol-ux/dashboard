-- ==============================================================================
-- 9. Tabla: entregas_bitacora (Módulo de Entrega Blindada)
-- Propósito: Sanciona la entrega física final. Adjunta evidencias (hasta 5 fotos),
-- observaciones del estado del vestido y la firma del cliente al momento de recibir.
-- ==============================================================================
CREATE TABLE entregas_bitacora (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contrato_id UUID NOT NULL REFERENCES contratos(id) ON DELETE CASCADE,
    observaciones TEXT NOT NULL,
    fotos_urls JSONB DEFAULT '[]'::jsonb, -- Array de URLs generadas desde Supabase Storage
    firma_cliente_base64 TEXT, -- Firma incrustada desde public url
    estado_firma TEXT DEFAULT 'Pendiente', -- 'Pendiente' | 'Firmado'
    fecha_entrega TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    usuario_id UUID REFERENCES auth.users(id) ON DELETE SET NULL, -- Asesora despachadora
    tipo_entrega TEXT DEFAULT 'EVENTO',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 10. Tabla: asesoras
-- Propósito: Maestro de personal operativo vinculado a una sede específica.
-- ==============================================================================
CREATE TABLE asesoras (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre_completo TEXT NOT NULL,
    sede_id UUID REFERENCES sedes(id) ON DELETE CASCADE,
    activo BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 11. Tabla: referidores
-- Propósito: Almacena los aliados o referidores que tendrán un link dinámico.
-- ==============================================================================
CREATE TABLE referidores (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre_aliado TEXT NOT NULL,
    slug_unico TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 12. Tabla: codigos_descuento
-- Propósito: Registra los códigos generados a los clientes desde el link de un referidor.
-- ==============================================================================
CREATE TABLE codigos_descuento (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    codigo_seguridad TEXT NOT NULL UNIQUE,
    referidor_id UUID NOT NULL REFERENCES referidores(id) ON DELETE CASCADE,
    nombre_quinceanera TEXT NOT NULL,
    telefono_quinceanera TEXT NOT NULL,
    correo_quinceanera TEXT NOT NULL,
    fecha_evento DATE,
    usado BOOLEAN DEFAULT FALSE,
    fecha_uso TIMESTAMP WITH TIME ZONE,
    contrato_id UUID REFERENCES contratos(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

