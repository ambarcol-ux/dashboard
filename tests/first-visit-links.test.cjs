const assert=require('node:assert/strict');const compile=require('./compile.cjs');
const {signVisitLink,verifyVisitLink,visitManagementLink,whatsappPhone}=compile('lib/first-visit-links.ts');
const {followupPlan,followupUrgency}=compile('lib/first-visit-followup.ts');
const id='00000000-0000-0000-0000-000000000001',key='test-only-secret',expires=Date.now()+10000;
const token=signVisitLink(id,expires,key);
assert.equal(verifyVisitLink(token,key).id,id);
assert.equal(verifyVisitLink(token,'wrong'),null);
assert.equal(verifyVisitLink(token,key,expires),null);
assert.equal(verifyVisitLink(token.replace('000000000001','000000000002'),key),null);
assert.equal(verifyVisitLink(token+'.extra',key),null);
assert.equal(verifyVisitLink(token,''),null);
assert.ok(visitManagementLink('https://example.invalid',id,expires,key).includes('/gestionar#'));
assert.equal(whatsappPhone('300 123 4567'),'573001234567');
assert.deepEqual(Array.from(followupPlan('2026-10-01','2026-11-10')),['2026-10-03','2026-10-11','2026-10-19','2026-10-26','2026-11-03']);
assert.deepEqual(Array.from(followupPlan('2026-10-01','2026-10-04')),['2026-10-02','2026-10-03']);
assert.equal(followupPlan('','').length,0);assert.equal(followupPlan('2026-10-01','2026-10-01').length,0);
assert.equal(followupUrgency('2026-10-01',false,'EN SEGUIMIENTO','2026-10-08'),'vencido');
assert.equal(followupUrgency('2026-10-01',false,'NO CONTACTAR','2026-10-08'),'cerrado');
console.log('First visit signed links and followup rules passed');
